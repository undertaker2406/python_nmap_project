"""Host Discovery: quét thiết bị sống trong mạng nội bộ.

- Dùng `nmap -sn` (ping sweep, nhanh, không scan port).
- Ghi kết quả ra data/targets.txt + DB.
- Tự động chạy OS detection cho các host vừa tìm.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import nmap

from config import TARGETS_FILE, NMAP_TIMEOUT
from core.scanner import BaseScanner, ScanError
from database import targets_repo
from modules.os_detection import OSDetector
from utils.logger import get_logger, get_scan_logger
from utils.network_utils import get_local_subnet, reverse_dns
from utils.validator import validate_target

log = get_logger(__name__)


class HostDiscovery(BaseScanner):
    def __init__(self, nmap_path: str | None = None,
                 os_detector: OSDetector | None = None):
        super().__init__(nmap_path)
        self.slog = get_scan_logger("host_discovery")
        self.os_detector = os_detector or OSDetector()

    # ---- public API ----

    def discover(self, subnet: str | None = None,
                 run_os_detection: bool = True,
                 write_file: bool = True) -> list[dict]:
        """Quét mạng, trả list host đã tìm được.

        Args:
            subnet: CIDR / IP / hostname. Mặc định lấy LAN hiện tại (/24).
            run_os_detection: chạy OS detection cho từng host tìm được.
            write_file: ghi danh sách IP ra data/targets.txt.
        """
        target = validate_target(subnet) if subnet else get_local_subnet()
        self.slog.info("[DISC] starting host discovery on %s", target)

        try:
            self.nm.scan(hosts=target, arguments="-sn -T4", timeout=NMAP_TIMEOUT)
        except nmap.PortScannerError as e:
            self.slog.exception("[DISC] nmap error")
            raise ScanError(f"nmap -sn failed: {e}") from e

        hosts = self._parse_hosts()
        self.slog.info("[DISC] found %d live host(s)", len(hosts))

        if not hosts:
            log.warning("HostDiscovery: không tìm thấy host nào trên %s", target)
            return []

        # 1. Ghi DB
        for h in hosts:
            targets_repo.upsert(h["ip"], **{
                "hostname":    h["hostname"],
                "mac_address": h["mac"],
                "vendor":      h["vendor"],
                "status":      "up",
            })

        # 2. Ghi file
        if write_file:
            self._write_targets_file(hosts)

        # 3. OS detection (yêu cầu đề bài)
        if run_os_detection:
            ips = [h["ip"] for h in hosts]
            self.slog.info("[DISC] running OS detection for %d host(s)", len(ips))
            os_results = self.os_detector.detect(ips)
            for h in hosts:
                res = os_results.get(h["ip"], {})
                if "host" in res:
                    h["os"] = self._extract_os(res["host"]) or None

        self.slog.info("[DISC] done: %d host(s) saved", len(hosts))
        return hosts

    # ---- internals ----

    def _parse_hosts(self) -> list[dict]:
        out: list[dict] = []
        for ip in self.nm.all_hosts():
            data = self.nm[ip]
            if data.get("status", {}).get("state") != "up":
                continue

            addrs = data.get("addresses") or {}
            mac = addrs.get("mac")
            vendor = (data.get("vendor") or {}).get(mac, "") if mac else ""

            hostname = ""
            hostnames = data.get("hostnames") or []
            for hn in hostnames:
                if hn.get("name"):
                    hostname = hn["name"]
                    break
            if not hostname:
                hostname = reverse_dns(ip) or ""

            out.append({
                "ip": ip,
                "hostname": hostname,
                "mac": mac or "",
                "vendor": vendor,
            })
        return out

    def _write_targets_file(self, hosts: list[dict]) -> None:
        TARGETS_FILE.parent.mkdir(parents=True, exist_ok=True)
        lines = []
        lines.append(f"# Auto-generated by NetRecon at {datetime.utcnow().isoformat()}Z")
        for h in hosts:
            parts = [h["ip"]]
            if h["hostname"]:
                parts.append(f"({h['hostname']})")
            if h["mac"]:
                parts.append(h["mac"])
            if h["vendor"]:
                parts.append(h["vendor"])
            lines.append(" ".join(parts))

        TARGETS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
        log.info("Wrote %d host(s) to %s", len(hosts), TARGETS_FILE)
        self.slog.info("[DISC] targets.txt updated (%d hosts)", len(hosts))

    # abstract compliance — run() gọi discover()
    def run(self, targets=None, profile="quick", custom_args="", **kw) -> dict:
        subnet = targets[0] if targets else None
        hosts = self.discover(subnet=subnet, **kw)
        return {h["ip"]: h for h in hosts}